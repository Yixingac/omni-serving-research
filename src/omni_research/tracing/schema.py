"""Application/agent trace schema (``omni_research.agent_trace/v1``).

A trace is a JSONL file. Line 1 is a ``trace_header``; then ``span`` and ``event`` records in any
order; optionally a final ``trace_footer``. All span/event times are integer nanoseconds in the
header's clock domain (``monotonic_ns`` of one host process unless stated otherwise). The header
carries a wall-clock anchor so times can be joined with server events stamped with
``time.time_ns()`` on the same host. See docs/tracing/TRACE_SCHEMA.md.

This module is the single source of truth for record shapes; the writer and the validator both
use it. It deliberately depends on the standard library only.
"""

from __future__ import annotations

import dataclasses
import enum
import uuid
from dataclasses import dataclass, field
from typing import Any

SCHEMA_VERSION = "omni_research.agent_trace/v1"


class SpanKind(str, enum.Enum):
    """Layer of an application-level span. Serving/GPU layers live in other files."""

    SESSION = "session"  # one agent session (a conversation / task episode)
    INTERACTION = "interaction"  # one user turn inside a session
    AGENT_STEP = "agent_step"  # one reasoning/acting step of the agent
    MODEL_REQUEST = "model_request"  # one call to the serving system
    TOOL_CALL = "tool_call"  # one tool invocation by the agent
    WAIT = "wait"  # explicit idle interval (user think time, pacing, backoff)


class Status(str, enum.Enum):
    OK = "ok"
    ERROR = "error"
    CANCELLED = "cancelled"
    TIMEOUT = "timeout"


class SourceKind(str, enum.Enum):
    """Where the trace came from. Synthetic traces must say so."""

    OBSERVED = "observed"  # recorded from a real agent run against a real server
    SYNTHETIC = "synthetic"  # generated by a workload generator; no real execution
    REPLAY = "replay"  # recorded while replaying another trace


class ContentPolicy(str, enum.Enum):
    """What the trace stores about message/media content. Default: nothing but sizes."""

    NONE = "none"  # sizes, counts and durations only
    HASHED = "hashed"  # plus SHA-256 digests of content
    PUBLIC = "public"  # content of public/synthetic inputs may be included verbatim


MODALITIES = ("text", "audio", "image", "video")

# Attributes each span kind must carry (beyond the common ids), checked by the validator.
REQUIRED_ATTRS: dict[SpanKind, tuple[str, ...]] = {
    SpanKind.SESSION: (),
    SpanKind.INTERACTION: (),
    SpanKind.AGENT_STEP: (),
    SpanKind.MODEL_REQUEST: ("input_modalities", "output_modalities", "endpoint"),
    SpanKind.TOOL_CALL: ("tool_name",),
    SpanKind.WAIT: ("reason",),
}

# Correlation ids each kind must carry.
REQUIRED_IDS: dict[SpanKind, tuple[str, ...]] = {
    SpanKind.SESSION: ("session_id",),
    SpanKind.INTERACTION: ("session_id", "interaction_id"),
    SpanKind.AGENT_STEP: ("session_id", "step_id"),
    SpanKind.MODEL_REQUEST: ("session_id", "request_id"),
    SpanKind.TOOL_CALL: ("session_id",),
    SpanKind.WAIT: ("session_id",),
}

# Standard event names inside a model_request span (client-observed streaming milestones).
EV_REQUEST_SENT = "request_sent"
EV_RESPONSE_HEADERS = "response_headers"
EV_FIRST_TEXT = "first_text_token"
EV_FIRST_AUDIO = "first_audio_chunk"
EV_TEXT_CHUNK = "text_chunk"
EV_AUDIO_CHUNK = "audio_chunk"
EV_COMPLETE = "response_complete"
EV_ERROR = "error"
EV_CANCEL = "cancel"


def new_id(prefix: str = "") -> str:
    """Opaque, collision-resistant id (uuid4 hex), optionally prefixed for readability."""
    return f"{prefix}{uuid.uuid4().hex}"


@dataclass
class ClockDomain:
    """How to interpret times in this trace.

    ``mono_anchor_ns`` and ``wall_anchor_ns`` were read back-to-back at trace start, so
    ``wall = wall_anchor_ns + (t - mono_anchor_ns)`` converts a span time to the host's
    ``time.time_ns()``. Times from different hosts are not comparable unless an alignment
    method is recorded in ``alignment``.
    """

    domain: str  # "monotonic_ns" (time.monotonic_ns of `host`) or "synthetic_ns"
    host: str
    pid: int
    mono_anchor_ns: int
    wall_anchor_ns: int
    anchor_uncertainty_ns: int  # half-width of the two reads that formed the anchor
    alignment: str = "single-host"  # or e.g. "ntp-unverified" for cross-host joins

    def to_wall_ns(self, t_ns: int) -> int:
        return self.wall_anchor_ns + (t_ns - self.mono_anchor_ns)

    def from_wall_ns(self, wall_ns: int) -> int:
        return self.mono_anchor_ns + (wall_ns - self.wall_anchor_ns)


@dataclass
class TraceHeader:
    trace_id: str
    clock: ClockDomain
    source: dict[str, Any]  # {"kind": SourceKind, "generator": str, "seed": int|None, ...}
    content_policy: str = ContentPolicy.NONE.value
    workload: dict[str, Any] = field(default_factory=dict)
    notes: str = ""
    schema: str = SCHEMA_VERSION
    record_type: str = "trace_header"

    def to_dict(self) -> dict[str, Any]:
        return dataclasses.asdict(self)


@dataclass
class Span:
    trace_id: str
    span_id: str
    kind: str
    name: str
    start_ns: int
    end_ns: int | None = None
    parent_span_id: str | None = None
    session_id: str | None = None
    interaction_id: str | None = None
    step_id: str | None = None
    request_id: str | None = None
    depends_on: list[str] = field(default_factory=list)  # span_ids that must finish first
    status: str = Status.OK.value
    attributes: dict[str, Any] = field(default_factory=dict)
    record_type: str = "span"

    def to_dict(self) -> dict[str, Any]:
        return dataclasses.asdict(self)

    @property
    def duration_ns(self) -> int | None:
        return None if self.end_ns is None else self.end_ns - self.start_ns


@dataclass
class Event:
    trace_id: str
    span_id: str
    name: str
    time_ns: int
    attributes: dict[str, Any] = field(default_factory=dict)
    record_type: str = "event"

    def to_dict(self) -> dict[str, Any]:
        return dataclasses.asdict(self)


@dataclass
class TraceFooter:
    trace_id: str
    span_count: int
    event_count: int
    closed_ns: int
    dropped_records: int = 0
    record_type: str = "trace_footer"

    def to_dict(self) -> dict[str, Any]:
        return dataclasses.asdict(self)


def span_from_dict(d: dict[str, Any]) -> Span:
    names = {f.name for f in dataclasses.fields(Span)}
    return Span(**{k: v for k, v in d.items() if k in names})


def event_from_dict(d: dict[str, Any]) -> Event:
    names = {f.name for f in dataclasses.fields(Event)}
    return Event(**{k: v for k, v in d.items() if k in names})


def header_from_dict(d: dict[str, Any]) -> TraceHeader:
    clock = ClockDomain(**d["clock"])
    rest = {k: v for k, v in d.items() if k not in ("clock",)}
    names = {f.name for f in dataclasses.fields(TraceHeader)}
    return TraceHeader(clock=clock, **{k: v for k, v in rest.items() if k in names})
